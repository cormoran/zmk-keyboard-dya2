#!/usr/bin/env python3
"""Commit a fully frozen West manifest on a release branch."""

import argparse
import pathlib
import re
import subprocess

import yaml


ROOT = pathlib.Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "config/west-dependency.yml"
SHA = re.compile(r"[0-9a-f]{40}\Z")
VERSION = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*\Z")


def run(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("version", help="release version and branch suffix")
    args = parser.parse_args()
    version = args.version
    if not VERSION.fullmatch(version) or ".." in version or version.endswith("."):
        parser.error("version must be a single safe Git ref component")

    changes = run("git", "status", "--porcelain", "--untracked-files=normal", "--", ".", ":!dependencies")
    if changes:
        parser.error("Git checkout must be clean")
    if pathlib.Path(run("west", "topdir")).resolve() != ROOT:
        parser.error("initialize the standalone West workspace in this checkout first")
    if pathlib.Path(run("west", "manifest", "--path")).resolve() != ROOT / "config/west-standalone.yml":
        parser.error("expected config/west-standalone.yml as the active manifest")

    frozen = yaml.safe_load(run("west", "manifest", "--freeze", "--active-only"))["manifest"]
    projects = frozen["projects"]
    if not projects:
        parser.error("West manifest contains no projects")
    for project in projects:
        path = pathlib.PurePosixPath(project["path"])
        if path.parts[0] != "dependencies" or len(path.parts) < 2:
            parser.error(f"unexpected dependency path: {path}")
        if not SHA.fullmatch(project["revision"]):
            parser.error(f"dependency is not frozen: {project['name']}")
        project["path"] = pathlib.PurePosixPath(*path.parts[1:]).as_posix()
    frozen["self"] = {"path": "config"}

    branch = f"release/{version}"
    run("git", "check-ref-format", "--branch", branch)
    run("git", "switch", "-c", branch)
    MANIFEST.write_text(
        "# Generated by scripts/prepare-release.py. Do not edit on release branches.\n"
        + yaml.safe_dump({"manifest": frozen}, sort_keys=False),
        encoding="utf-8",
    )
    run("git", "add", str(MANIFEST.relative_to(ROOT)))
    run("git", "commit", "-m", f"Release {version}: pin West dependencies")
    print(f"release_branch={branch}")
    print(f"release_sha={run('git', 'rev-parse', 'HEAD')}")


if __name__ == "__main__":
    main()
